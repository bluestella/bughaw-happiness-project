#!/usr/bin/env bash
# Writes .env.e2e from the running LOCAL Supabase stack (`supabase start`).
# .env.e2e is gitignored. It holds the local service-role key, which only the
# test tooling (tests/e2e/support/admin.ts) reads — never the app. See
# docs/ui-testing.md §1.1 and docs/security.md.
set -euo pipefail
cd "$(dirname "$0")/../.."

status="$(supabase status -o env 2>/dev/null)" || {
  echo "Local Supabase is not running. Start it with: supabase start" >&2
  exit 1
}
get() { printf '%s\n' "$status" | sed -n "s/^$1=\"\{0,1\}\([^\"]*\)\"\{0,1\}$/\1/p" | head -n1; }

api_url="$(get API_URL)"
case "$api_url" in
  http://127.0.0.1:*|http://localhost:*) ;;
  *) echo "Refusing: API_URL '$api_url' is not a local Supabase." >&2; exit 1 ;;
esac

umask 077
cat > .env.e2e <<ENV
# Generated by scripts/e2e/env.sh — LOCAL Supabase only. Do not commit.
NEXT_PUBLIC_SUPABASE_URL=$api_url
NEXT_PUBLIC_SUPABASE_ANON_KEY=$(get ANON_KEY)
SUPABASE_SERVICE_ROLE_KEY=$(get SERVICE_ROLE_KEY)
E2E_BASE_URL=http://localhost:3100
E2E_INGEST_SECRET=e2e-ingest-secret
ENV
echo "Wrote .env.e2e for $api_url"
